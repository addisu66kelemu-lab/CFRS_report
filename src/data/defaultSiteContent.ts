const SITE_CONTENT_STORAGE_KEY = 'central_ethiopia_site_modules_content_v1';

export function loadSiteContent(): SiteModulesContent {
  try {
    const raw = localStorage.getItem(SITE_CONTENT_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      // Merge with initial in case schema added fields
      return {
        home: { ...INITIAL_SITE_CONTENT.home, ...(parsed.home || {}) },
        services: { ...INITIAL_SITE_CONTENT.services, ...(parsed.services || {}) },
        about: { ...INITIAL_SITE_CONTENT.about, ...(parsed.about || {}) },
        resources: { ...INITIAL_SITE_CONTENT.resources, ...(parsed.resources || {}) },
        contact: { ...INITIAL_SITE_CONTENT.contact, ...(parsed.contact || {}) },
        zonesFees: { ...INITIAL_SITE_CONTENT.zonesFees, ...(parsed.zonesFees || {}) }
      };
    }
  } catch (err) {
    console.error('Failed to load site content from localStorage:', err);
  }
  return INITIAL_SITE_CONTENT;
}

export function saveSiteContent(content: SiteModulesContent): void {
  try {
    localStorage.setItem(SITE_CONTENT_STORAGE_KEY, JSON.stringify(content));
  } catch (err) {
    console.error('Failed to save site content to localStorage:', err);
  }
}

export function resetSiteContentToDefault(): SiteModulesContent {
  try {
    localStorage.removeItem(SITE_CONTENT_STORAGE_KEY);
  } catch {}
  return INITIAL_SITE_CONTENT;
}
